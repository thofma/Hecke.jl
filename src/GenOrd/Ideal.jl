# Two-element form requires the first generator to be the element of the coefficient ring.
# Testing the parent of first generator is too strict: for example literal 2
#   is not a ZZRingElem; similarly for t and 1//t both having k(t) as a parent,
#   t is in k[t] and 1//t is in KInftyRing (can be used as first generators
#   in finite/infinite orders).
function _as_coefficient_ring_elem(O::GenOrd, a::RingElement)
  R = base_ring(O)

  # if already in coefficient ring: can be used directly
  parent(a) === R && return a
  # if not in the base field, cannot be used for two-element representation
  if parent(a) !== base_field(field(O))
    return nothing
  end

  num, den = integral_split(a, R)
  return is_unit(den) ? divexact(num, den) : nothing
end
# no integral_split for IntegerUnion, do coersion directly
_as_coefficient_ring_elem(O::GenOrd, a::IntegerUnion) = base_ring(O)(a)

function ideal(O::GenOrd, a::RingElement, b::GenOrdElem)
  @req parent(b) === O "generators must belong to the given order"

  g = _as_coefficient_ring_elem(O, a)
  if g === nothing
    return ideal(O, elem_type(O)[O(a), b])
  else
    return is_zero(g) ? GenOrdIdl(O, b) : GenOrdIdl(O, g, b)
  end
end

ideal(O::GenOrd, a::RingElement, b::RingElement) = ideal(O, a, O(b))
ideal(O::GenOrd, a::GenOrdElem, b::RingElement) = ideal(O, elem_type(O)[a, O(b)])
ideal(O::GenOrd, a::GenOrdElem, b::GenOrdElem) = ideal(O, elem_type(O)[a, b])

ideal(O::GenOrd, a::RingElement) = GenOrdIdl(O, O(a))
ideal(O::GenOrd, a::GenOrdElem) = GenOrdIdl(O, a)

function ideal(O::GenOrd, v::Vector{<:GenOrdElem})
  @req all(x -> parent(x) === O, v) "generators must belong to the given order"
  isempty(v) && return ideal(O, zero(O))

  return GenOrdIdl(O, v)
end


function ideal(O::GenOrd, M::MatElem; M_in_hnf::Bool = false)
  n = degree(O)
  @req base_ring(M) === coefficient_ring(O) "matrix must be over the coefficient ring of O"
  @req ncols(M) == n "matrix must have exactly degree(O) = $n columns"
  @req nrows(M) >= n "matrix must have at least degree(O) = $n rows"

  H = M_in_hnf ? M : hnf(M, :lowerleft)
  @hassert :GenOrd 1 !M_in_hnf || H == hnf(H, :lowerleft)

  # the canonical lower-left HNF basis lives in the bottom n rows
  # also ensure that we materialize a view
  if nrows(H) > n || H isa AbstractAlgebra.Generic.MatSpaceView
    H = sub(H, nrows(H) - n + 1:nrows(H), 1:n)
  end

  return GenOrdIdl(O, H)
end

function AbstractAlgebra.zero(a::GenOrdIdl)
  O = a.order
  return GenOrdIdl(O, O(0))
end

has_2_elem(A::GenOrdIdl) = isdefined(A, :gen_two)

function is_zero(I::GenOrdIdl)
  if I.is_zero == 0
    if isdefined(I, :princ_gen)
      I.is_zero = is_zero(I.princ_gen) ? 1 : 2
    elseif isdefined(I, :gen_one) && isdefined(I, :gen_two)
      I.is_zero = is_zero(I.gen_one) && is_zero(I.gen_two) ? 1 : 2
    else
      @hassert :GenOrd 1 isdefined(I, :basis_matrix)
      # NOTE: assure_has_basis_matrix calls is_zero, so read field directly
      I.is_zero = is_zero(I.basis_matrix) ? 1 : 2
    end
  end

  return I.is_zero == 1
end

@doc raw"""
    is_one(A::GenOrdIdl) -> Bool
    is_unit(A::GenOrdIdl) -> Bool

Tests if $A$ is the trivial ideal generated by $1$.
"""
function is_one(I::GenOrdIdl)
  if isdefined(I, :norm)
    return is_one(norm(I; copy = false))
  end
  return is_one(minimum(I; copy = false))
end

is_unit(I::GenOrdIdl) = isone(I)

