function Hecke.divexact(A::GenOrdIdl, b::RingElem)
  is_zero(A) && return A

  O = order(A)
  b = _make_canonical_in(O, b)
  is_unit(b) && return A

  bm = divexact(basis_matrix(A; copy = false), b)
  B = ideal(O, bm; M_in_hnf = true)

  if has_princ_gen(A)
    # Coerce the base-ring scalar b through the base field before embedding it
    #   into O.F before dividing.
    bF = O.F(base_field(O.F)(b))
    B.princ_gen = O(divexact(O.F(A.princ_gen), bF))
  end

  return B
end


function has_minimum(A::GenOrdIdl)
  return isdefined(A, :minimum)
end

function Hecke.minimum(A::GenOrdIdl; copy::Bool = true)
  assure_has_minimum(A)
  if copy
    return deepcopy(A.minimum)::elem_type(base_ring(order(A)))
  else
    return A.minimum::elem_type(base_ring(order(A)))
  end
end

# for the principal ideal <alpha>: m in alpha*O <=> m/alpha in O.
# smallest such m (the minimum) is denominator of alpha^-1
function _minimum_principal(O::GenOrd, alpha::GenOrdElem)
  return _make_canonical_in(O, denominator(inv(data(alpha)), O))
end

# for <p, alpha> normal, the minimum is gcd(p, min(<alpha>))
function _minimum_2elem_normal(O::GenOrd, gen_one::RingElem, gen_two::GenOrdElem)
  return _make_canonical_in(O, gcd(gen_one, _minimum_principal(O, gen_two)))
end

function assure_has_minimum(A::GenOrdIdl)
  if has_minimum(A)
    return nothing
  end

  O = order(A)

  if has_2_elem_normal(A)
    A.minimum = _minimum_2elem_normal(O, A.gen_one, A.gen_two)
  elseif isone(basis(O; copy = false)[1])
    A.minimum = deepcopy(basis_matrix(A; copy = false)[1, 1])
  else
    M = basis_matrix(A; copy = false)
    d = prod([M[i, i] for i = 1:nrows(M)])
    v = transpose(matrix(map(base_ring(O), coordinates(O(d)))))
    fl, s = can_solve_with_solution(M, v, side = :left)
    @assert fl
    den = denominator(s[1]//d)
    for i = 2:ncols(s)
      den = lcm(den, denominator(s[i]//d))
    end

    A.minimum = _make_canonical_in(O, den)
  end

  return nothing
end

