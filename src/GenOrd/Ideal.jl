@doc raw"""
    basis_matrix(A::GenOrdIdl) -> Mat

Return the basis matrix of $A$.
"""
function Hecke.basis_matrix(A::GenOrdIdl{S, T}; copy::Bool = true) where {S, T}
  assure_has_basis_matrix(A)
  return (copy ? deepcopy(A.basis_matrix) : A.basis_matrix)::dense_matrix_type(elem_type(T))
end

function assure_has_basis_matrix(A::GenOrdIdl)
  if isdefined(A, :basis_matrix)
    return nothing
  end
  O = order(A)
  n = degree(O)

  if iszero(A)
    A.basis_matrix = zero_matrix(base_ring(O), n, n)
    return nothing
  end

  if has_princ_gen(A)
    A.basis_matrix = hnf(representation_matrix(A.princ_gen), :lowerleft)
    return nothing
  end

  @hassert :GenOrd 1 has_2_elem(A)

  if has_2_elem_normal(A)
    # minimum is cheap here, so we can build the basis via a modular hnf.
    m = minimum(A; copy = false)
    # V is [ m*I ; M_{gen_two mod m} ],  where M_x is the representation matrix of x
    V = vcat(scalar_matrix(base_ring(O), n, m), representation_matrix(mod(A.gen_two, m)))
    A.basis_matrix = sub(hnf_modular_eldiv_left!(V, m), n+1:2*n, 1:n)
    return nothing
  end

  V = hnf(reduce(vcat, [representation_matrix(x) for x in [O(A.gen_one), A.gen_two]]), :lowerleft)
  A.basis_matrix = sub(V, n+1:2*n, 1:n)
  return nothing
end

