function Base.deepcopy_internal(I::GenOrdIdl{S, T}, dict::IdDict) where {S, T}
  J = GenOrdIdl(order(I))
  for f in fieldnames(typeof(I))
    f === :order && continue
    if isdefined(I, f)
      setfield!(J, f, Base.deepcopy_internal(getfield(I, f), dict))
    end
  end
  return J
end

