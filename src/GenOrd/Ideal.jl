# Multiplying an integral ideal by a *base ring* scalar is equivalent to
#   scaling the ideal basis matrix.
# Internal helper for base-ring scalar case
function _ideal_by_scaling_matrix(c, I::GenOrdIdl)
  O = order(I)
  # we must ensure canonical form, to keep HNF canonical
  c = _make_canonical_in(O, c)

  is_zero(c) && return ideal(O, c)
  is_one(c) && return I
  return ideal(O, c * basis_matrix(I; copy = false); M_in_hnf = true)
end

# This is the check for "scalar is in the base ring"
# Since x is GenOrdElem, it is integral, so we need to check if it is in the base field
function _is_in_base_field(x::GenOrdElem)
  a = data(x)
  for i in 1:degree(parent(a)) - 1
    is_zero(coeff(a, i)) || return false
  end
  return true
end

function Base.:*(x::GenOrdElem, O::GenOrd)
  return ideal(O, x)
end

function Base.:*(x::GenOrdElem, I::GenOrdIdl{S, T}) where {S, T}
  O = order(I) # note that this has concrete type for type inference
  @req parent(x) === O "Element and ideal must belong to the same order"

  if _is_in_base_field(x)
    c, den = integral_split(coeff(data(x), 0), base_ring(O))
    @assert is_one(den)
    return _ideal_by_scaling_matrix(c, I)
  end

  return ideal(O, x) * I
end

Base.:*(x::GenOrdIdl, y::GenOrdElem) = y * x

# For A = <m, alpha> with m = minimum(A) in m-normal two-element representation
#   A^{-1} = O + beta*O, with beta = d_c * alpha^{-1}, d_c = part of denom(alpha^{-1}) coprime to m.
# We compute this ideal as <d_m, gamma>/d_m, with
#   gamma = numerator(alpha^{-1}, O) = d*alpha^{-1}; d = denom(alpha^{-1})
#   d_m = part of denom(alpha^{-1}) supported at m.
# We then have <d_m, gamma> = d_m*A^{-1} normal
function _inv_2elem_normal(O::GenOrd, A::GenOrdIdl)
  @hassert :GenOrd 1 has_2_elem_normal(A)

  m = minimum(A; copy = false)
  is_unit(m) && return fractional_ideal(A)

  gamma, d = integral_split(inv(data(A.gen_two)), O)
  d_m = _make_canonical_in(O, ppio(d, m)[1])

  Ai = ideal(O, d_m, _reduce_gen_two_2elem_normal(gamma, d_m))
  Ai.gens_normal = A.gens_normal
  Ai.norm = _make_canonical_in(O, divexact(d_m^degree(O), norm(A; copy = false)))
  @hassert :GenOrd 2 defines_2_normal(Ai)
  return fractional_ideal(Ai, d_m)
end

function inv(I::GenOrdIdl)
  @req !is_zero(I) "Ideal must be nonzero"

  O = order(I)

  if is_maximal_known_and_maximal(O) && has_2_elem_normal(I)
    B = _inv_2elem_normal(O, I)
    return B
  end

  # (O : A) is inverse iff A is coprime to the conductor (otherwise A is not invertible)
  return _inv_impl(HNFRedTrait(), O, I)
end

