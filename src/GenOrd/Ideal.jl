function prime_dec_nonindex(O::GenOrd{S, T}, p::RingElem, degree_limit::Int = 0, lower_limit::Int = 0) where {S, T}
  @req parent(p) === base_ring(O) "p must come from the base ring of O"

  F = field(O)
  B = base_field(F)
  a = gen(F)

  K, mK = residue_field(base_ring(O), p)

  fmodp = map_coefficients(defining_polynomial(O.F); cached = false) do c
    num, den = integral_split(c, base_ring(O))
    mK(num) // mK(den)
  end
  fact = factor(fmodp)

  result = Vector{Tuple{GenOrdIdl{S, T}, Int}}(undef, length(fact))
  for (i, (fac, e)) in enumerate(fact)
    f = degree(fac)
    facnew = map_coefficients(y -> B(preimage(mK, y)), fac, cached = false)

    # facnew(a) is integral at p, but a itself need not be globally integral,
    #   since we only require the defining polynomial to be locally integral at p.
    # To bring it back into O, scale by the denominator (which is coprime to p);
    #   this is equivalent to taking the numerator directly.
    b = numerator(facnew(a), O)

    # We want a P-normal two-element presentation, i.e. v_P(b) = 1.
    # Since we are in the case of p not dividing the index, we have a good candidate b = g(a).
    #
    # v_P(<p,b>) = min[v_P(p), v_P(b)] = 1.
    # Ramified case   (e > 1): v_P(p) = e > 1, so v_P(b) = 1 is forced.
    # Unramified case (e = 1): v_P(b) can exceed 1, in which case
    #   v_P(b + p) = min(v_P(b), 1) = 1
    # For other primes Q over p, v_Q(b) > 0 would give v_Q(<p, b>) > 0,
    #   giving <p,b> subset of Q, contradicting <p, b> = P.
    #
    # In the unramified case we need to check if v_P(b) == 1.
    # One possibility is to check if p*N(P) = p^{f+1} divides N(b)
    #   and if it doesn't, we must have v_P(b) == 1.
    # Unlike the number field case, b can be zero (single inert prime over p),
    #   which is also covered by adding p.
    if e == 1 && (is_zero(b) || divides(norm(b), p^(f + 1))[1])
      b = b + O(p)
    end

    I = ideal(O, p, b)
    I.gens_normal = p
    I.is_prime = 1
    I.splitting_type = e, f
    I.norm = p^f
    I.minimum = p

    # inert prime
    if f == degree(O)
      I.princ_gen = O(p)
      I.is_principal = 1
    end

    result[i] = (I,e)
  end
  return result
end

function Hecke.valuation(A::GenOrdIdl{S, T}, p::GenOrdIdl{S, T}) where {S, T}
  @req !is_zero(A) "A is zero"

  O = order(A)
  e = 0
  if has_2_elem_normal(p)
    beta = Hecke.numerator(inv(O.F(p.gen_two)), O)
    newA = fractional_ideal(beta*A, p.gen_one)
    while is_integral(newA)
      e += 1
      newA = fractional_ideal(numerator(beta*newA; copy = false), p.gen_one)
    end
  else
    newA = Hecke.colon(A,p)
    while is_integral(newA)
      e+=1
      newA = Hecke.colon(newA,fractional_ideal(p))
    end
  end
  return e
end


function Hecke.factor(A::GenOrdIdl{S, T}) where {S, T}
  O = A.order
  N = norm(A)
  factors = factor(N)
  primes = Dict{GenOrdIdl{S, T},Int}()
  for (f,e) in factors
    for (p,r) in prime_decomposition(O,f)
      p_val = valuation(A, p)
      if p_val != 0
        primes[p] = p_val
      end
    end
  end
  return primes
end

# For the Dedekind-Kummer criterion we need to consider the local (at p) defining polynomial f.
# In general, we do not need the defining polynomial to be monic;
#   we can make it monic in the base field and then consider its localization.
# Currently, we demand that f is monic "globally" (that is, leading coefficient is 1),
#   so it is enough to check the valuations of the denominators.

# The local version of is_defining_polynomial_nice:
#   checks whether the polynomial is monic and the coefficient valuations are non-negative.
function _is_defining_polynomial_nice_at(O::GenOrd, p::RingElem)
  @req parent(p) === base_ring(O) "p must lie in the coefficient ring of O"
  f = defining_polynomial(field(O))
  is_one(leading_coefficient(f)) || return false

  R = base_ring(O)
  for c in coefficients(f)
    divides(denominator(c, R), p)[1] && return false
  end

  return true
end

function is_index_divisor(O::GenOrd, p::RingElem)
  @req parent(p) === base_ring(O) "p must lie in the coefficient ring of O"
  is_equation_order(O) && return false

  num, den = integral_split(det(basis_matrix_inverse(O)), base_ring(O))
  # if p divides the numerator, it divides the index;
  # if p divides the denominator, the order is not maximal at p (cannot use Dedekind-Kummer)
  return divides(num, p)[1] || divides(den, p)[1]
end

function prime_decomposition(O::GenOrd{S, T}, p::RingElem, degree_limit::Int = degree(O), lower_limit::Int = 0; cached::Bool = true) where {S, T}
  if _is_defining_polynomial_nice_at(O, p) && !is_index_divisor(O, p)
    return prime_dec_nonindex(O, p, degree_limit, lower_limit)
  else
    return prime_dec_gen(O, p, degree_limit, lower_limit)
  end
end

function prime_dec_gen(O::GenOrd{S, T}, p::RingElem, degree_limit::Int = degree(O), lower_limit::Int = 0) where {S, T}
  Ip = pradical(O, p)
  lp = _decomposition(O, ideal(O, p), Ip, p)
  #=z = Tuple{ideal_type(O), Int}[]
  for (Q, e) in lp
    if degree(Q) <= degree_limit && degree(Q) >= lower_limit
      push!(z, (Q, e))
    end
  end
  return z
  =#
  return lp
end

function residue_field(R::PolyRing{QQBarFieldElem}, p::PolyRingElem{QQBarFieldElem})
  @assert degree(p) == 1
  @assert is_monic(p)
  c = -coeff(p, 0)
  K = base_ring(R)
  f = MapFromFunc(R, K, q -> q(c), x -> R(x))
  return K, f
end

function Hecke.pradical(O::GenOrd, p::RingElem)
  R, mR = residue_field(parent(p), p)

#  @assert characteristic(F) == 0 || (isfinite(F) && characteristic(F) > degree(O))
  if characteristic(R) == 0 || characteristic(R) > degree(O)
    @vprintln :GenOrd 1 "using trace-radical for $p"
    rad = radical_basis_trace
  elseif isa(R, Generic.RationalFunctionField)
    @vprintln :GenOrd 1 "non-perfect case for radical for $p"
    rad = radical_basis_power_non_perfect
  else
    @vprintln :GenOrd 1 "using radical-by-power for $p"
    rad = radical_basis_power
  end
  return ideal(O, rad(O,p); M_in_hnf = true)
end

function _basis_uniformizer(P::GenOrdIdl, p::RingElem, f::Int)
  # We have one prime above p.
  # If we are in maximal (at p) order, at least one element of the basis
  #   must have valuation exactly 1 (otherwise all of them are in P^2).
  q = p^(f + 1)
  for b in basis(P)
    divides(norm(b), q)[1] || return b
  end

  return nothing # non-maximal at p: no certified uniformizer
end

function _idempotent_uniformizer(P::GenOrdIdl, p::RingElem, f::Int, idempotent::GenOrdElem)
  O = order(P)

  # From structure algebra decomposition, we have idempotent e_j such that
  #   e_j = 1 mod P_j and e_j = 0 mod P_i for i != j
  # We have v_P(u) >= 1 and v_Q(u) = 0 for Q != P above p
  u = one(O) - idempotent

  q = p^(f + 1)
  divides(norm(u), q)[1] || return u

  # v_P(u) >= 2. Try shifting by idempotent without changing the valuation
  #   at other primes Q != P above p
  # If we have basis element b of valuation 1 we have v_P(u + b*idempotent) = 1
  #   and the valuation at other primes stays 0 (due to idempotent)
  # As above: such a basis element is guaranteed in p-maximal order
  #   but if not found, then we just won't have gen_two set
  for b in basis(P)
    u2 = u + idempotent*b
    divides(norm(u2), q)[1] || return u2
  end

  return nothing
end

function _decomposition(O::GenOrd{S, T}, I::GenOrdIdl{S, T}, Ip::GenOrdIdl{S, T}, p::RingElem) where {S, T}
  #I is an ideal lying over p
  #Ip is the p-radical
  Ip1 = Ip + I
  A, OtoA = StructureConstantAlgebra(O, Ip1, p)

  AtoO = pseudo_inv(OtoA)
  ideals, AA = _from_algs_to_ideals(A, OtoA, AtoO, Ip1, p)

  pcount = length(ideals)

  # check if we have inert prime: we then have principal ideal
  if pcount == 1 && ideals[1][1].splitting_type[2] == degree(O)
    P = ideals[1][1]
    P.splitting_type = 1, degree(O)

    P.gen_one = p
    P.gen_two = O(p)
    P.gens_normal = p
    P.princ_gen = O(p)
    P.is_principal = 1

    ideals[1] = (P, 1)
    return ideals
  end

  for i in 1:pcount
    P = ideals[i][1]
    f = P.splitting_type[2]

    # find uniformizer (gen_two)
    P_uni = if pcount == 1
      _basis_uniformizer(P, p, f)
    else
      idem  = AtoO(AA[i][2](one(AA[i][1])))
      _idempotent_uniformizer(P, p, f, idem)
    end

    # if we have found uniformizer: set normal representation
    if P_uni !== nothing
      P.gen_one = p
      P.gen_two = P_uni
      P.gens_normal = p
    end

    e = valuation(ideal(O, p), P)
    P.splitting_type = e, f
    ideals[i] = (P, e)
  end

  return ideals
end

function StructureConstantAlgebra(O::GenOrd, I::GenOrdIdl, p::RingElem)
  FQ, phi = residue_field(base_ring(O), p)
  StructureConstantAlgebra(O, I, p, phi)
end

function StructureConstantAlgebra(O::GenOrd, I::GenOrdIdl, p::RingElem, phi)
  @assert order(I) === O

  n = degree(O)
  bmatI = basis_matrix(I)

  basis_elts = Vector{Int}()
  for i = 1:n
    if is_coprime(bmatI[i, i], p)
      continue
    end

    push!(basis_elts, i)
  end

  r = length(basis_elts)
  FQ = codomain(phi)

  if r == 0
    A = zero_algebra(FQ)

    local _image_zero

    let A = A
      function _image_zero(a::GenOrdElem)
        return A()
      end
    end

    local _preimage_zero

    let O = O
      function _preimage_zero(a::AssociativeAlgebraElem)
        return O()
      end
    end

    OtoA = Hecke.AbsOrdToAlgAssMor{typeof(O), elem_type(FQ)}(O, A, _image_zero, _preimage_zero)
    return A, OtoA
  end

  BO = basis(O)
  mult_table = Array{elem_type(FQ), 3}(undef, r, r, r)
  for i = 1:r
    M = representation_matrix(BO[basis_elts[i]])
    #TODO: write version of reduce rows mod hnf
    if r != degree(O)
      M = reduce_rows_mod_hnf!(M, bmatI, basis_elts)
    end
    for j = 1:r
      for k = 1:r
        mult_table[i, j, k] = phi(M[basis_elts[j], basis_elts[k]])
      end
    end
  end

  if isone(BO[1])
    one = [zero(FQ) for _ in 1:r]
    one[1] = FQ(1)
    A = StructureConstantAlgebra(FQ, mult_table, one)
  else
    A = StructureConstantAlgebra(FQ, mult_table)
  end
  if is_commutative(O)
    A.is_commutative = 1
  end

  local _image

  let I = I, A = A, basis_elts = basis_elts, FQ = FQ
    function _image(a::GenOrdElem)
      c = coordinates(mod(a, I))
      return A([phi(O.R(c[i])) for i in basis_elts ])
    end
  end

  local _preimage

  let BO = BO, basis_elts = basis_elts, r = r
    function _preimage(a::AssociativeAlgebraElem)
      ca = coefficients(a)
      return sum(preimage(phi, ca[i]) * BO[basis_elts[i]] for i in 1:length(ca))
    end
  end

  OtoA = GenOrdToAlgAssMor{typeof(O), elem_type(FQ)}(O, A, _image, _preimage)

  return A, OtoA
end

# Reduces the rows of M in `rows` modulo N in place.
# Assumes that N is in lowerleft HNF.
function reduce_rows_mod_hnf!(M::MatElem, N::MatElem, rows::Vector{Int})
  for i in rows
    for j = ncols(M):-1:1
      if iszero(M[i, j])
        continue
      end

      t = div(M[i, j], N[j, j])
      for k = 1:j
        M[i, k] = M[i, k] - t*N[j, k]
      end
    end
  end
  return M
end

