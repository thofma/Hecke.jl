function _in(a::MatrixElem, M::EmbeddedModule{_PID}, ::Val{with_coordinates} = Val(false)) where {with_coordinates}
  if isdefined(M, :basis_matrix_inverse)
    t = _tmp_mat_overring(M, nrows(a))
    mul!(t, a, basis_matrix_inverse(M))
    return _has_preimage(fraction_map(M), t, Val(with_coordinates))
  end
  fl, u = can_solve_with_solution(basis_matrix(M), a; side = :left)
  if !fl
    if with_coordinates
      return false, zero_matrix(ring(M), nrows(a), rank(M))
    else
      return false
    end
  end
  return _has_preimage(fraction_map(M), u, Val(with_coordinates))
end

# Dedekind domain with given pseudo-element
function _in((a, id)::Tuple, M::EmbeddedModule{_DD})
  MB = basis_matrix(M)
  if a isa Vector
    a = matrix(overring(M), 1, length(a), a)
  end
  return Hecke._contained_in_span_of_pseudohnf(a, id, MB; shape = :lowerleft)
end

function _in(a::Vector, M::EmbeddedModule{_DD}, ::Val{with_coordinates} = Val(false)) where {with_coordinates}
  @req length(a) == ambient_rank(M) "The ambient coordinates have the wrong length"
  B = matrix(overring(M), 1, length(a), a)
  if with_coordinates
    fl, c = _in(B, M, Val(true))
    return fl, c[1, :]
  end
  return _in(B, M)
end

function _in(a::MatrixElem, M::EmbeddedModule{_DD}, ::Val{with_coordinates} = Val(false)) where {with_coordinates}
  @req ncols(a) == ambient_rank(M) "The matrix has the wrong number of columns"
  B = basis_matrix(M)
  if with_coordinates
    c = zero_matrix(overring(M), nrows(a), nrows(B))
  end
  for i in 1:nrows(a)
    if with_coordinates
      fl, v = Hecke._contained_in_span_of_pseudohnf(a[i:i, :], B, Val(true); shape = :lowerleft)
      if !fl
        return false, c
      end
      for j in 1:ncols(c)
        c[i, j] = v[1, j]
      end
    elseif !Hecke._contained_in_span_of_pseudohnf(a[i:i, :], B; shape = :lowerleft)
      return false
    end
  end
  return with_coordinates ? (true, c) : true
end

function _in(N::PMat, M::EmbeddedModule{_DD})
  return Hecke._spans_subset_of_pseudohnf(N, basis_matrix(M); shape = :lowerleft)
end

_map_to_ambient(x, M) = x

_map_to_ambient(x::MatrixElem, M::EmbeddedModule) = x

function Base.in(x, M::EmbeddedModule)
  return _in(_map_to_ambient(x, M), M)
end

function Base.in(x::PseudoElement, M::EmbeddedModule)
  if _ring_type(ring(M)) === _PID
    return _in(_map_to_ambient(element(x), M), M)
  else
    y = _map_to_ambient(element(x), M)
    return _in((y, fractional_ideal(x)), M)
  end
end

function issubset(N::EmbeddedModule, M::EmbeddedModule)
  _check_compatible(N, M)
  return _in(_short_generator_matrix(N), M)
end

function ==(M::EmbeddedModule, N::EmbeddedModule)
  M === N && return true
  is_compatible(M, N) || return false
  return issubset(M, N) && issubset(N, M)
end

function _embedded_module_hash(M::EmbeddedModule{_PID}, h::UInt)
  if !isdefined(M, :canonical_basis_matrix)
    M.canonical_basis_matrix = Hecke._hnf_integral(basis_matrix(M), ring(M); shape = :lowerleft)
  end
  B = M.canonical_basis_matrix::dense_matrix_type(overring(M))
  return hash(B, h)
end

function _embedded_module_hash(M::EmbeddedModule{_DD}, h::UInt)
  P = basis_matrix(M)
  return hash(Hecke.coefficient_ideals(P), hash(matrix(P), h))
end

function Base.hash(M::EmbeddedModule, h::UInt)
  h = hash(ring(M), h)
  h = hash(overring(M), h)
  h = hash(overstructure(M), h)
  return _embedded_module_hash(M, h)
end

@doc raw"""
    module_index(N::EmbeddedModule, M::EmbeddedModule; check = true)

For PID coefficients, return the index ideal of `N` in `M`. It is the principal
ideal of `ring(M)` generated by the determinant of the inclusion matrix with
respect to bases of `N` and `M`, and is independent of these bases. Equal modules,
including zero modules, have the unit ideal as their index ideal.

If `check` is `true`, require compatible modules with the same rank and `N`
contained in `M`. Use `gen` to obtain a normalized generator of the index ideal.
"""
function module_index(N::EmbeddedModule{_PID}, M::EmbeddedModule; check = true)
  if check
    @req rank(N) == rank(M) "Index not defined"
    @req issubset(N, M) "Modules must be contained in each other"
  end
  if has_full_rank(N)
    i = _preimage(fraction_map(M), divexact(det(basis_matrix(N)), det(basis_matrix(M))))
    return ideal(ring(M), i)
  end
  fl, T = can_solve_with_solution(basis_matrix(M), basis_matrix(N); side = :left)
  @assert fl
  return ideal(ring(M), _preimage(fraction_map(M), det(T)))
end
