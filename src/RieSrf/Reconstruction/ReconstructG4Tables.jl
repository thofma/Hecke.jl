#
#  ReconstructG4Tables.jl : the characteristics of the genus 4 reconstruction
#
#  Characteristics are bit tuples (a1, ..., a4, b1, ..., b4), written here as
#  bit strings "a1a2a3a4b1b2b3b4". Used by ReconstructG4.jl: the tritangent
#  planes (eq. (4.1) of the paper), the pairs (H_i, H_i') = (chi_i, chi_i + eta)
#  for eta = 00001000, the Jacobian nullvalues (Fay's generalized Jacobi
#  formula) for them, and the bitangents of the Prym (generic case) resp. the
#  lines through its Weierstrass points (vanishing theta null case) that
#  belong to the pairs (Milne's bijection). From the Magma package
#  reconstructing-g4.
#
################################################################################

# "0110..." -> (0, 1, 1, 0, ...)
_characteristic(bits::AbstractString) = Tuple(Int(c - '0') for c in bits)

# xi_1, ..., xi_5: the tritangent planes of xi_1..xi_4 are x_k = 0, the one of
# xi_5 is x_1 + ... + x_4 = 0
_g4_tritangent_basis() = _characteristic.(["11101110", "10100010", "11100010", "10100110", "01100100"])

# the pairs (chi_i, chi_i + eta)
_g4_tritangent_pairs() = [_characteristic.([c, c[1:4] * "1" * c[6:8]]) for c in
  ["01100100", "01000100", "01010100", "01110100", "01010110",
   "01000110", "01000111", "01110111", "01000101", "01100101"]]

# The bitangents l_i of the Prym that belong to the pairs, as indices into the
# 28 bitangents of _aronhold_bitangents (generic case) resp. the 28 lines of
# _g4_hyperelliptic_prym_lines (vanishing theta null case)
_g4_prym_bitangent_selection() = (10, 23, 4, 20, 17, 9, 12, 1, 5, 11)
_g4_weierstrass_line_selection() = (24, 20, 21, 23, 17, 16, 15, 14, 19, 26)

# The Jacobian nullvalues D(xi_1, .., chi, .., xi_4) (chi in position k) for
# the characteristics chi of the pairs: D = pi^4 (s1 prod theta[S1] + s2 prod
# theta[S2]). table[i][j][k] = (S1, S2, (s1, s2)) for the pair i, j = 1 (H_i)
# or 2 (H_i'), k = 1..4. In the data, the comment line of (i, j) is followed
# by the lines "s1 S1" and "s2 S2" for k = 1, .., 4. Pair 1, H is xi_5, so its
# entries are the normalizations D(xi_1, .., xi_5, .., xi_4) of eq. (4.1).
# (Checked numerically: D = pi^4 (s1 T1 + s2 T2) for all 80 entries.)
function _g4_jacobian_nullvalue_table()
  terms = [split(line) for line in split(_g4_jacobian_nullvalue_data(), '\n')
           if !isempty(strip(line)) && !startswith(line, '#')]
  @assert length(terms) == 160
  formula(t1, t2) = (_characteristic.(t1[2:7]), _characteristic.(t2[2:7]),
                     (parse(Int, t1[1]), parse(Int, t2[1])))
  formulas = [formula(terms[2*n - 1], terms[2*n]) for n in 1:80]
  return [[[formulas[8*(i - 1) + 4*(j - 1) + k] for k in 1:4] for j in 1:2] for i in 1:10]
end

