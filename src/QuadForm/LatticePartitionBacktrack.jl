@doc raw"""
    automorphism_group(forms::Vector{ZZMatrix}, [vector_set, labels,
                       unsigned_labels]) -> Vector{ZZMatrix}, ZZRingElem

Given square integer matrices `forms`, the first of which is symmetric and
positive definite, return generators and the order of the group of all
integer matrices `g` with `g*F*transpose(g) == F` for all `F` in `forms`.
For good performance the first form should be LLL reduced.

The group acts on the vectors up to the smallest norm, with respect to the
first form, for which they generate the lattice. Alternatively a set of
vectors can be given, up to sign: `vector_set` is a list of tuples whose
first entry is a vector, and `labels` and `unsigned_labels` are lists of
integers, one for each vector, or empty. The label of `-v` is that of `v`
with the signed part negated. Of a set with labels the vectors with the norms
and the label of a standard basis vector in the set are kept, of a set
without labels those up to the smallest norm for which they generate. The
kept vectors have to generate the lattice, as they do if the set contains the
standard basis. Then exactly those `g` are returned which map the kept set to
itself and respect norms and labels.

With `invariant = true` the caller asserts that every `g` which preserves the
first form and maps generators of the lattice among the kept vectors to
vectors with the same labels preserves the other forms, maps the kept set to
itself and respects norms and labels. Then an automorphism which is found is
only verified against the first form and these labels. This holds if the
other forms and the labels are derived from the first form in a way which is
invariant under the group, as for projections to characteristic sublattices
and scalar products with a Weyl vector [BH].

The second entries of the tuples are not used. In the output of the targeted
enumeration they are the norms of the vector with respect to the forms, which
are recomputed here.
"""
function automorphism_group(forms::Vector{ZZMatrix}, vector_set = (),
                            labels = Int[], unsigned_labels = UInt[];
                            kwargs...)
  if nrows(forms[1]) == 0
    return ZZMatrix[identity_matrix(ZZ, 0)], one(ZZRingElem)
  end
  S = isempty(vector_set) ? ShortVectors(forms; kwargs...) :
        short_vectors(forms, vector_set, labels, unsigned_labels; kwargs...)
  chain = stabilizer_chain(S)
  return ZZMatrix[matrix(ZZ, g) for g in chain.generators], chain.order
end

@doc raw"""
    isometry(forms1::Vector{ZZMatrix}, forms2::Vector{ZZMatrix},
             [vector_set1, vector_set2, labels1, labels2]) -> Bool, ZZMatrix

Given two lists of square integer matrices as in `automorphism_group`, decide
whether there is an integer matrix `g` with `g*forms2[i]*transpose(g) ==
forms1[i]` for all `i`, and return such a matrix if it exists.

If sets of vectors with labels are given, then `g` is moreover required to
map vectors of `vector_set1` which generate the lattice to vectors in
`vector_set2` with the same labels: the standard basis vectors in the set
and, if some are missing, further vectors of it. The second set must contain
every such image.
"""
function isometry(forms1::Vector{ZZMatrix}, forms2::Vector{ZZMatrix},
                  vector_set1 = (), vector_set2 = (), labels1 = Int[],
                  labels2 = Int[]; kwargs...)
  n = nrows(forms1[1])
  no = false, zero_matrix(ZZ, 0, 0)
  if n != nrows(forms2[1]) || length(forms1) != length(forms2) ||
     is_symmetric.(forms1) != is_symmetric.(forms2)
    return no
  end
  n == 0 && return true, zero_matrix(ZZ, 0, 0)
  # The search finds a matrix g of rank n with g*forms2[i]*transpose(g) ==
  # forms1[i]; it is invertible over the integers if and only if the
  # determinants agree.
  det(forms1[1]) == det(forms2[1]) || return no
  if isempty(vector_set1)
    # An isometry maps the vectors of the first lattice of norm at most N
    # onto those of the second. The first set consists of the vectors up to
    # some N <= `bound`, which is their largest norm if the norms fit into an
    # `Int`. Then the second set is cut at N exactly, not by hashed colours.
    list, bound = generating_vectors(forms1[1])
    S1 = ShortVectors(forms1, list; kwargs...)
    if fits(Int, bound)
      V = S1.vectors
      GV = compress_forms(forms1[1:1])[1] * V
      bound = ZZ(maximum(j -> sum(V[i, j] * GV[i, j] for i in 1:n),
                         1:number_of_vectors(S1)))
    end
    S2 = ShortVectors(forms2, enumerate_vectors(forms2[1], bound);
                      source = S1, kwargs...)
  else
    S1 = short_vectors(forms1, vector_set1, labels1, UInt[]; kwargs...)
    S2 = short_vectors(forms2, vector_set2, labels2, UInt[];
                       source = S1, kwargs...)
  end
  walk = Walk(S2, Reference(S1), :follow, true)
  if advance!(walk, 0) && extend!(walk, 0)
    return true, matrix(ZZ, walk.isometry)
  end
  return no
end


