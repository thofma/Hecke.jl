################################################################################
#
#  The finite set of short vectors
#
################################################################################

# A finite set V union -V of lattice vectors, together with the bilinear
# forms the isometries have to preserve and a colouring they have to respect.
#
# Column j of `vectors` is v_j; only one of v_j, -v_j is stored. A *point* is a
# signed index: p > 0 stands for v_p and p < 0 for -v_{-p}. In arrays the
# point p > 0 has the index p and the point -p has the index nv + p, see
# `index`.
#
# `exact_forms` are the forms F_1, ..., F_m as given; F_1 is symmetric and
# positive definite, the others are arbitrary. The search does not look at
# them one by one. It uses
#
#     `form` = F_1 + sum_{i > 1} (c_i * F_i + d_i * transpose(F_i))
#
# with fixed pseudo-random c_i and d_i (d_i = 0 if F_i is symmetric), computed
# modulo 2^64. We write <x, y> = x * form * transpose(y); this is not
# symmetric in general. An isometry preserves <x, y>, and up to the unlikely
# event of a collision <p, x> determines all F_i(p, x) and F_i(x, p). A
# collision only weakens the tests of the search, see `search_form`.
#
# A label is a pair of a signed and an unsigned integer supplied by the
# caller for every vector; the label of -v is that of v with the signed part
# negated, see `label`. The *colour* of a point consists of its norm <v, v>
# and its label; `palette` lists the colours in increasing order, and
# `colours` gives for every point, by its index, the position of its colour
# in the palette. An isometry maps every point to a point of the same colour.
#
# `complete` tells whether there are no labels and the set was cut down by
# the norm alone. Then every isometry of the forms which maps the given set
# to itself maps this set to itself and respects the colours.
#
# `tables[j]` caches the scalar products of all points with v_j, see
# `tabulate!`.
# A set of points, by their indices: the point with index i is in the set if
# bit (i - 1) % 64 of the word (i - 1) >> 6 + 1 is set.
const PointSet = Vector{UInt64}

# The empty set of points with indices up to `N`.
point_set(N::Int) = zeros(UInt64, (N + 63) >> 6)

Base.@propagate_inbounds has(set::PointSet, i::Int) =
  set[(i - 1) >> 6 + 1] >> ((i - 1) & 63) & 1 == 1

# Add the point to the set if it is not in it, and remove it otherwise.
Base.@propagate_inbounds function toggle!(set::PointSet, i::Int)
  w = (i - 1) >> 6 + 1
  set[w] = xor(set[w], UInt64(1) << ((i - 1) & 63))
end

# The number of common points of two sets.
function count_common(a::PointSet, b::PointSet)
  c = 0
  @inbounds @simd for w in 1:length(a)
    c += count_ones(a[w] & b[w])
  end
  return c
end

# The scalar products of all points with one vector v: `sets[r]` is the set
# of points p with <p, v> = values[r]. The values are sorted and symmetric,
# values[r] == -values[end + 1 - r], which gives the scalar products with -v
# as well.
struct Table
  values::Vector{Int}
  sets::Vector{PointSet}
end

struct ShortVectors
  exact_forms::Vector{ZZMatrix}
  form::Matrix{Int}
  vectors::Matrix{Int}                  # n x nv, column j is v_j
  form_vectors::Matrix{Int}             # form * vectors
  labels::Vector{Int}                   # signed part of the label of v_j
  unsigned_labels::Vector{UInt}
  palette::Vector{Tuple{Int, Int, UInt}}
  colours::Vector{Int}
  index::Dict{Vector{Int}, Int}         # v_j => j or -v_j => -j
  complete::Bool
  tables::Vector{Table}
  work::Vector{Int}
  budget::Base.RefValue{Int}
  buffer::Vector{Int}                   # work space of `apply`
end

dim(S::ShortVectors) = size(S.vectors, 1)

number_of_vectors(S::ShortVectors) = size(S.vectors, 2)

# Conversion between points and their indices in arrays.
index(S::ShortVectors, p::Int) = p > 0 ? p : number_of_vectors(S) - p

function point(S::ShortVectors, i::Int)
  nv = number_of_vectors(S)
  return i <= nv ? i : nv - i
end

# The label of the point `p`.
label(S::ShortVectors, p::Int) =
  (p > 0 ? S.labels[p] : -S.labels[-p], S.unsigned_labels[abs(p)])

# A fixed bijection of the machine integers which scrambles them. It is used
# wherever several numbers are combined into one, so that the result does
# not depend on the version of Julia.
function mix(x::Int)
  z = reinterpret(UInt, x) + 0x9e3779b97f4a7c15
  z = xor(z, z >> 30) * 0xbf58476d1ce4e5b9
  z = xor(z, z >> 27) * 0x94d049bb133111eb
  return reinterpret(Int, xor(z, z >> 31))
end

# The matrix `form` of `ShortVectors`.
#
# The search computes with `Int` and lets the arithmetic wrap around. This is
# harmless: reduction modulo 2^64 is a ring homomorphism, so an equation
# between scalar products which holds over the integers also holds for the
# reduced values. Every test of the search is such an equation, satisfied by
# all isometries; hence wrapping never discards an isometry. It may let a
# wrong candidate pass, which is why a complete image is checked with exact
# arithmetic, see `is_isometry`. Only the coordinates of the short vectors
# have to fit into an `Int`.
function search_form(exact_forms::Vector{ZZMatrix})
  n = nrows(exact_forms[1])
  modulo_word(F) = Int[BigInt(F[i, j]) % Int for i in 1:n, j in 1:n]
  form = modulo_word(exact_forms[1])
  for i in 2:length(exact_forms)
    F = modulo_word(exact_forms[i])
    form += mix(i) * F
    if !is_symmetric(exact_forms[i])
      form += mix(-i) * transpose(F)
    end
  end
  return form
end

# All non-zero vectors of norm at most `bound` with respect to the positive
# definite form `G`, up to sign.
function enumerate_vectors(G::ZZMatrix, bound = maximum(diagonal(G)))
  if all(x -> nbits(x) < 62, G)
    return Vector{Int}[v for (v, _) in __short_vectors(G, nothing, bound)]
  end
  list = _short_vectors_gram_integral(Vector, G, ZZ(0), bound, ZZRingElem)
  return Vector{Int}[Int.(v) for (v, _) in list]
end

# The lattice generated by some vectors of Z^n: the rows of `basis`, which is
# in Hermite normal form, generate it.
mutable struct Generated
  basis::ZZMatrix
end

Generated(n::Int) = Generated(zero_matrix(ZZ, n, n))

# Whether the lattice is all of Z^n.
is_everything(L::Generated) = isone(L.basis)

# Whether the lattice generated by the rows of `H`, which is in Hermite normal
# form, contains the vector `v`.
function is_generated(H::Matrix{Int}, v::AbstractVector{Int})
  n = size(H, 1)
  w = collect(v)
  @inbounds for i in 1:n
    pivot = findfirst(k -> H[i, k] != 0, 1:n)
    pivot === nothing && break
    q, r = divrem(w[pivot], H[i, pivot])
    r == 0 || return false
    for k in pivot:n
      w[k] -= q * H[i, k]
    end
  end
  return all(iszero, w)
end

# Add the columns of `vectors` with the given indices to the generators.
# Returns whether this made the lattice larger.
function enlarge!(L::Generated, vectors::Matrix{Int}, indices)
  n = nrows(L.basis)
  new = matrix(ZZ, Int[vectors[i, j] for j in indices, i in 1:n])
  basis = sub(hnf(vcat(L.basis, new)), 1:n, 1:n)
  basis == L.basis && return false
  L.basis = basis
  return true
end

# Whether the given vectors generate Z^n.
function generate(list::Vector{Vector{Int}}, n::Int)
  L = Generated(n)
  for chunk in Iterators.partition(list, 16 * n)
    enlarge!(L, reduce(hcat, chunk), 1:length(chunk))
    is_everything(L) && return true
  end
  return false
end

# All non-zero vectors of norm at most N with respect to `G`, up to sign,
# which generate the lattice, and N. Here N is the smallest diagonal entry of
# `G` if that suffices, and otherwise the largest, for which the standard
# basis is among the vectors. Trying more bounds would cost more
# enumerations than it saves; `shortest_generating` cuts the set down.
function generating_vectors(G::ZZMatrix)
  bound = minimum(diagonal(G))
  list = enumerate_vectors(G, bound)
  if bound < maximum(diagonal(G)) && !generate(list, nrows(G))
    bound = maximum(diagonal(G))
    list = enumerate_vectors(G, bound)
  end
  return list, bound
end

# The set V is given by `list`, up to sign, and has to generate the lattice;
# by default it is `generating_vectors` of the first form. Not all of it is
# kept, unless `everything` is set:
#
#   * If there are labels, the standard basis vectors have to be in `list`.
#     The vectors with the colour of a standard basis vector are kept; they
#     contain the image of the standard basis under any isometry respecting
#     the labels.
#   * If there are no labels, the vectors up to the smallest norm for which
#     they generate the lattice are kept.
#   * If an isometry from `source` onto this lattice is sought, the vectors
#     with a colour occurring in `source` are kept.
#
# In each case the set is mapped to itself by all automorphisms, and onto
# the set of `source` by all isometries. It is essential that the set
# generates the lattice and does not merely span the space: otherwise the
# search would run through the isometries of the sublattice it generates.
function ShortVectors(exact_forms::Vector{ZZMatrix},
                      list::Vector{Vector{Int}} =
                        generating_vectors(exact_forms[1])[1];
                      labels::Vector{Int} = zeros(Int, length(list)),
                      unsigned_labels::Vector{UInt} = zeros(UInt, length(list)),
                      source = nothing, everything::Bool = false,
                      cache_max_bytes::Int = CACHE_MAX_BYTES)
  form = search_form(exact_forms)
  n = size(form, 1)
  all_vectors = Matrix{Int}(undef, n, length(list))
  for (j, v) in enumerate(list)
    all_vectors[:, j] = v
  end

  # the colours of v_j and of -v_j
  all_form_vectors = form * all_vectors
  plus = Vector{Tuple{Int, Int, UInt}}(undef, length(list))
  minus = similar(plus)
  for j in 1:length(list)
    s = 0
    @inbounds @simd for i in 1:n
      s += all_vectors[i, j] * all_form_vectors[i, j]
    end
    plus[j] = (s, labels[j], unsigned_labels[j])
    minus[j] = (s, -labels[j], unsigned_labels[j])
  end

  labelled = any(!iszero, labels) || any(!iszero, unsigned_labels)
  if source !== nothing
    needed = Set(source.palette)
    keep = Int[j for j in 1:length(list)
               if plus[j] in needed || minus[j] in needed]
  elseif everything
    keep = collect(1:length(list))
  elseif labelled
    needed = Set{Tuple{Int, Int, UInt}}()
    for j in 1:length(list)
      v = view(all_vectors, :, j)
      if count(!iszero, v) == 1
        sum(v) == 1 && push!(needed, plus[j])
        sum(v) == -1 && push!(needed, minus[j])
      end
    end
    keep = Int[j for j in 1:length(list)
               if plus[j] in needed || minus[j] in needed]
  else
    gram = search_form(exact_forms[1:1])
    keep = shortest_generating(all_vectors, length(exact_forms) == 1 ?
                                 all_form_vectors : gram * all_vectors)
  end
  nv = length(keep)
  palette = source === nothing ?
              sort!(unique!(vcat(plus[keep], minus[keep]))) : source.palette
  # The colour 0 is given to points whose colour does not occur in `source`.
  function position(c)
    r = searchsortedfirst(palette, c)
    return r <= length(palette) && palette[r] == c ? r : 0
  end
  colours = vcat(Int[position(plus[j]) for j in keep],
                 Int[position(minus[j]) for j in keep])

  index = sizehint!(Dict{Vector{Int}, Int}(), nv)
  for j in 1:nv
    v = list[keep[j]]
    if starts_negative(v)
      index[-v] = -j
    else
      index[v] = j
    end
  end
  return ShortVectors(exact_forms, form, all_vectors[:, keep],
                      all_form_vectors[:, keep], labels[keep],
                      unsigned_labels[keep], palette, colours, index,
                      source === nothing && !everything && !labelled,
                      [Table(Int[], PointSet[]) for _ in 1:nv],
                      zeros(Int, nv), Ref(8 * cache_max_bytes), zeros(Int, n))
end

# The indices of the columns of `vectors` up to the smallest norm N for which
# the vectors of norm at most N generate the lattice; `gram_vectors` is the
# product of the Gram matrix with `vectors`. This set only depends on the
# lattice and not on its basis, which `canonical_form` relies on.
function shortest_generating(vectors::Matrix{Int}, gram_vectors::Matrix{Int})
  n, nv = size(vectors)
  norms = zeros(Int, nv)
  for j in 1:nv, i in 1:n
    norms[j] += vectors[i, j] * gram_vectors[i, j]
  end
  # The standard basis vectors generate. If they are all there, N is at most
  # their largest norm, and only smaller norms have to be tried.
  units = Int[j for j in 1:nv if count(!iszero, view(vectors, :, j)) == 1 &&
                                 abs(sum(view(vectors, :, j))) == 1]
  upper = length(units) == n ? maximum(norms[units]) : typemax(Int)
  below = filter!(j -> norms[j] < upper, sortperm(norms))
  L = Generated(n)
  for chunk in Iterators.partition(below, 16 * n)
    before = L.basis
    enlarge!(L, vectors, chunk)
    is_everything(L) || continue
    # The vectors before the chunk do not generate, those up to its end do.
    # So N is the first norm ending in the chunk up to which they generate,
    # or the last norm of the chunk.
    for t in 1:(length(chunk) - 1)
      N = norms[chunk[t]]
      N == norms[chunk[t + 1]] && continue
      L = Generated(before)
      enlarge!(L, vectors, view(chunk, 1:t))
      is_everything(L) && return findall(<=(N), norms)
    end
    return findall(<=(norms[last(chunk)]), norms)
  end
  upper < typemax(Int) || error("the vectors do not generate the lattice")
  return findall(<=(upper), norms)
end

const CACHE_MAX_BYTES = 2^28

# The point with coordinate vector `w`, or 0 if `w` is not a short vector.
function find_point(S::ShortVectors, w::Vector{Int})
  starts_negative(w) || return get(S.index, w, 0)
  w .= .-w
  p = get(S.index, w, 0)
  w .= .-w
  return -p
end

# Whether the first non-zero entry of `w` is negative. Of v and -v, the one
# for which it is not is the key in `index`.
function starts_negative(w::AbstractVector{Int})
  for x in w
    x != 0 && return x < 0
  end
  return false
end

# The points e_1, ..., e_n.
function basis_points(S::ShortVectors)
  n = dim(S)
  basis = zeros(Int, n)
  e = zeros(Int, n)
  for i in 1:n
    e[i] = 1
    basis[i] = find_point(S, e)
    basis[i] != 0 || error("basis vector is not among the short vectors")
    e[i] = 0
  end
  return basis
end

# The coordinate vector of the point `p`.
function coordinates(S::ShortVectors, p::Int)
  v = S.vectors[:, abs(p)]
  return p < 0 ? -v : v
end

# The scalar product <i, x> of the points with indices i and x.
function product(S::ShortVectors, i::Int, x::Int)
  n, nv = size(S.vectors)
  j, k = i <= nv ? i : i - nv, x <= nv ? x : x - nv
  s = 0
  @inbounds @simd for l in 1:n
    s += S.vectors[l, j] * S.form_vectors[l, k]
  end
  return (i <= nv) == (x <= nv) ? s : -s
end

# The table for the vector of the point with index `x`, or `nothing`.
#
# Scalar products are first computed on demand. `demand` is the number of
# scalar products with the vector which are about to be computed; once those
# computed so far would have sufficed for all points, the table is filled,
# as long as the cache has room. So an easy search or one which only ever
# looks at few points tabulates little.
function tabulate!(S::ShortVectors, x::Int, demand::Int)
  nv = number_of_vectors(S)
  k = x <= nv ? x : x - nv
  isempty(S.tables[k].sets) || return S.tables[k]
  S.work[k] += demand
  (S.work[k] >= nv && S.budget[] > 0) || return nothing
  products = Int[product(S, j, k) for j in 1:nv]
  # The negative of the smallest machine integer is not its negative.
  typemin(Int) in products && return nothing
  values = Int[]
  for s in products, value in (s, -s)
    r = searchsortedfirst(values, value)
    (r > length(values) || values[r] != value) && insert!(values, r, value)
  end
  sets = [point_set(2 * nv) for _ in values]
  for j in 1:nv
    r = searchsortedfirst(values, products[j])
    toggle!(sets[r], j)
    toggle!(sets[length(values) + 1 - r], nv + j)
  end
  S.budget[] -= 2 * nv * length(values)
  return S.tables[k] = Table(values, sets)
end

# A number which combines, for all c, the numbers of points q in a set with
# <q, x> = c, where x is a point given by its index. The set is given by the
# indices `elements` of its points and as the set `members`.
function count_invariant(S::ShortVectors, elements::AbstractVector{Int},
                         members::PointSet, x::Int)
  table = tabulate!(S, x, length(elements))
  result = 0
  if table === nothing
    for i in elements
      result += mix(product(S, i, x))
    end
  else
    sign = x <= number_of_vectors(S) ? 1 : -1
    for (value, set) in zip(table.values, table.sets)
      result += mix(sign * value) * count_common(set, members)
    end
  end
  return result
end

