################################################################################
#
#  Partition backtracking for automorphisms, isometries and canonical forms
#  of definite lattices
#
################################################################################
#
#  Purpose
#  -------
#
#  This file is a self-contained implementation of partition backtracking
#  for definite integer lattices, possibly with additional bilinear forms.
#  It computes automorphism groups, isometries and canonical forms.
#  Structure like roots or invariant sublattices is detected
#  beforehand by the callers and handed over as additional forms and as
#  labels of the short vectors, see `automorphism_group` and [BH].
#
#  Everything lives in the submodule `Hecke.LatticePartitionBacktrack`, so the
#  short names used below (`Walk`, `Orbit`, `advance!`, ...) cannot clash with
#  anything else in Hecke. The only pieces of Hecke used are the exact
#  short-vector enumeration, Hermite normal forms and LLL reduction.
#
#
#  Mathematical setup
#  ------------------
#
#  Let G be the positive definite integral Gram matrix of a rank-n lattice. We
#  use row vectors, so an integral matrix M is an automorphism precisely when
#
#                         M * G * transpose(M) == G.                 (1)
#
#  Let V be all non-zero lattice vectors of norm at most B, stored up to
#  sign, where B is the smallest number for which these vectors generate the
#  lattice. An isometry preserves norms, so it permutes V union -V. We encode
#  v_j by the positive integer j and -v_j by -j, and call such a signed index
#  a *point*.
#
#  Let b_1, ..., b_m be points which generate the lattice. Every map of them
#  into V union -V which preserves all scalar products extends to a unique
#  automorphism, and all automorphisms arise in this way [BH, Lemma 3.2]. So
#  the automorphisms are found by searching for the possible images of such a
#  sequence in a finite set. It matters that V generates the lattice and does
#  not merely span the space: otherwise the maps would correspond to the
#  isometries of the sublattice generated by V. On the other hand V need not
#  contain a basis of the lattice, which would force B to be larger for some
#  lattices; this is why m may be larger than n.
#
#  More generally the input is a list of integral matrices F_1, ..., F_k,
#  where F_1 = G is as above and the others are arbitrary, also skew-symmetric
#  or not symmetric at all. Then (1) is required for every F_i, and the
#  scalar product <x, y> below stands for a fixed combination of all the
#  F_i(x, y) and F_i(y, x), see `ShortVectors`. The caller may also supply
#  the set V itself together with a label for every vector; then an
#  automorphism has to map every vector to a vector with the same label. The
#  norm and the label of a point make up its *colour*.
#
#
#  The search tree
#  ---------------
#
#  A node of the search tree is a sequence of points x_1, ..., x_d, which are
#  said to be *individualized*. It carries an ordered partition of points
#  into *cells*: two points are in the same cell if nothing that has been
#  computed tells them apart, given x_1, ..., x_d. At the root the cells are
#  the colours. When a point x is individualized, every cell is split by the
#  scalar products <p, x> of its points p, and further invariants split the
#  cells again, see `advance!`. The numbers produced on the way, such as the
#  sizes of the cells, form the *trace* of the node. The children of a node
#  are obtained by individualizing the points of one of its cells.
#
#  The partition and the trace of a node only depend on the node up to
#  isometry. So if an isometry maps (b_1, ..., b_d) to (x_1, ..., x_d), the
#  two nodes have the same trace, and x_{d+1} lies in the cell which
#  corresponds to the cell of b_{d+1}. This is all the search uses:
#
#    * Automorphisms. Fix a *reference path* b_1, ..., b_m, see `Reference`,
#      and walk through the nodes whose traces agree with those of the
#      reference, branching on the cells which contain the b_d. A node (x_1,
#      ..., x_m) which is reached describes the map b_d -> x_d.
#    * Isometries. The same, with the reference path in one lattice and the
#      walk in the other.
#    * Canonical forms. Among all leaves of the tree, take those with the
#      smallest traces, see `canonical_form`.
#
#  For the first two, only the cells containing the later b_d matter, and
#  the others are dropped; the cost of a node is then proportional to the
#  cells which matter. The recursion in `extend!` is the familiar pattern
#
#      choose a point of the cell -> refine the partition -> recurse.
#
#
#  From individual maps to the full group
#  --------------------------------------
#
#  Let H_i be the subgroup fixing b_1, ..., b_{i-1}. At outer step i the cell
#  of b_i consists of all possible images of b_i under H_i. Known generators
#  split those candidates into orbits. We search only one representative of
#  each not-yet-known orbit:
#
#    * a successful search supplies a new generator and enlarges the known
#      orbit of b_i;
#    * a failed search rules out the representative and its entire orbit under
#      the currently known subgroup.
#
#  When no candidates remain, the orbit is complete. Orbit-stabilizer gives
#
#                |Aut(G)| = product_i |b_i ^ H_i|.                  (3)
#
#  The matrices found at step i fix b_1, ..., b_{i-1}; retaining them by level
#  therefore gives a stabilizer chain and a certificate for the product in
#  (3). If -1 respects the labels it is an automorphism; this is used at the
#  first level.
#
#
#  Machine integers
#  ----------------
#
#  The search computes with `Int` and lets it wrap around, see `compress_forms`.
#  All its tests remain necessary conditions for an isometry. In return every
#  complete image is checked against (1) and against the labels in exact
#  arithmetic before it is accepted, see `is_isometry`, so the result is
#  correct for forms with entries of any size. The search is only effective
#  as long as the forms distinguish vectors modulo 2^64: on a sublattice where
#  they vanish modulo 2^64 it tries everything.
#
#
#  Reading map
#  -----------
#
#    `ShortVectors`      the finite set V union -V the group acts on
#    `Partition`         ordered partitions
#    `Reference`         a path of the search tree to compare with
#    `Walk`, `advance!`  walking through the search tree; the refinement
#    `extend!`           the depth-first search for one isometry
#    `Generator`, `Orbit`, `close!`
#                        explicit orbit computation on points
#    `stabilizer_chain`  the outer loop; best entry point for the algorithm
#    `automorphism_group`, `isometry`, `canonical_form`
#                        the interface used by Hecke
#
#
#  Extension points
#  ----------------
#
#    * Stronger refiners (Bacher polynomials, ...): add a step to `advance!`
#      which reports its numbers with `observe!`, as is done for the sums of
#      cells. Nothing else has to change.
#    * Threads: the searches for the images of different candidates at one
#      level of `stabilizer_chain` are independent, up to the cache of
#      scalar products in `ShortVectors`.
#
#
#  References
#  ----------
#
#  [BH] S. Brandhorst and T. Hofmann, "Automorphisms and canonical forms of
#       integer lattices", arXiv:2610.16753.
#
#  [PS97] W. Plesken and B. Souvignier, "Computing Isometries of Lattices",
#         Journal of Symbolic Computation 24 (1997), 327--334.
#         https://doi.org/10.1006/jsco.1996.0130
#
#  [Leo91] J. S. Leon, "Permutation Group Algorithms Based on Partitions, I:
#          Theory and Algorithms", Journal of Symbolic Computation 12 (1991),
#          533--583.
#          https://doi.org/10.1016/S0747-7171(08)80103-4
#
#  [Leo97] J. S. Leon, "Partitions, Refinements, and Permutation Group
#          Computation", in Groups and Computation II, DIMACS Series 28,
#          American Mathematical Society (1997), 123--158.
#
#  [Sim71] C. C. Sims, "Computation with Permutation Groups", Proceedings of
#          SYMSAC '71, ACM (1971), 23--28.
#          https://doi.org/10.1145/800204.806264
#
