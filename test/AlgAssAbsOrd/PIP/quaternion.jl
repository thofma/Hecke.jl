@testset "Definite quaternion algebras" begin
  # the quaternion algebra over QQ ramified exactly at p and infinity
  function definite_algebra(p)
    p == 2 && return quaternion_algebra(QQ, -1, -1)
    p % 4 == 3 && return quaternion_algebra(QQ, -1, -p)
    p % 8 == 5 && return quaternion_algebra(QQ, -2, -p)
    q = first(q for q in 3:4:1000 if is_prime(q) && jacobi_symbol(p, q) == -1)
    return quaternion_algebra(QQ, -p, -q)
  end

  # A fixed maximal order of the algebra ramified exactly at an odd prime p and
  # infinity, as maximal_order(A) is not the same order on every run:
  # Ibukiyama's Z + Z(1 + j)/2 + Z i(1 + j)/2 + Z (r + i)j/q in (-p, -q), for
  # the least prime q = 3 mod 8 with (p/q) = -1 and r^2 = -p mod q (Nagoya
  # Math. J. 88 (1982), Lemmas 1.1 and 1.2).
  function ibukiyama_order(p)
    q = first(q for q in 3:8:1000 if is_prime(q) && jacobi_symbol(p, q) == -1)
    r = first(r for r in 1:q if mod(r^2 + p, q) == 0)
    A = quaternion_algebra(QQ, -p, -q)
    e, i, j, k = basis(A)
    return order(A, [e, QQ(1, 2) * (e + j), QQ(1, 2) * (i + k),
                     QQ(1, q) * (r * j + k)]; isbasis = true)
  end

  # right ideals x O + m O, for fixed x in O, and the left ideals
  # O conj(x) + O m with the same principality
  coeffs = [[1, 2, 0, -1], [0, 1, 3, 1], [2, -1, 1, 1], [1, 1, 1, 3]]
  function test_ideals(O, k = length(coeffs))
    B = absolute_basis(O)
    xs = [O(sum(c[mod1(i, 4)] * elem_in_algebra(B[i]) for i in eachindex(B)))
          for c in coeffs[1:k]]
    right = [x * O + m * O for x in xs for m in (2, 3)]
    left = [O * conj(elem_in_algebra(x)) + m * O for x in xs for m in (2, 3)]
    return right, left
  end

  # the order generated by 1 and a right ideal I of prime norm of O, an
  # Eichler order of that level; I is the first of these ideals by the Hermite
  # normal form of their coordinates over QQ, as maximal_integral_ideals lists
  # them in a random order
  function eichler(O, l)
    A = algebra(O)
    if base_ring(A) isa QQField
      coords = x -> coefficients(x)
    else
      AQ, AQtoA = restrict_scalars(A, QQ)
      coords = x -> coefficients(preimage(AQtoA, x))
    end
    function key(J)
      B = absolute_basis(J)
      X = matrix(QQ, [coords(b)[k] for b in B, k in 1:length(B)])
      return vec(collect(Hecke._hnf_integral(X, :lowerleft)))
    end
    Is = Hecke.maximal_integral_ideals(O, l; side = :right)
    I = first(sort(Is; by = key))
    if base_ring(A) isa QQField
      return order(A, vcat([one(A)], basis(I)))
    end
    R = base_ring(O)
    one_row = pseudo_matrix(matrix(base_ring(A), 1, 4, coefficients(one(A))),
                            [1 * R])
    M = pseudo_hnf(vcat(basis_pmatrix(I), one_row), :lowerleft)
    return order(A, sub(M, 2:5, 1:4))
  end

  @testset "over QQ, against the generic test" begin
    for p in [11, 47]
      M = ibukiyama_order(p)
      A = algebra(M)
      @test is_maximal(M) && Hecke._reduced_disc(M) == p
      Z3M = order(A, vcat([one(A)], [3 * elem_in_algebra(b) for b in basis(M)]))
      for O in [M, eichler(M, 2), Z3M]
        right, left = test_ideals(O, 2)
        nprincipal = 0
        for (I, J) in zip(right, left)
          fl, beta = Hecke._is_principal_with_data(I, O)
          nprincipal += fl
          @test fl == Hecke._is_principal_with_data_bj(I, O)[1]
          @test fl == Hecke._is_principal(I, O)
          if fl
            @test beta * O == I
            @test normred(beta)^2 == norm(I, O)
          end
          flJ, gamma = Hecke._is_principal_with_data(J, O; side = :left)
          @test flJ == fl
          flJ && @test O * gamma == J
          # the exported functions, with the order given
          @test is_principal(I, O) == fl
          @test is_principal(J, O; side = :left) == fl
          flJ, gamma = is_principal_with_data(J, O; side = :left)
          @test flJ == fl
          flJ && @test O * gamma == J
          # and without it, where the default is O: a right (left) ideal of a
          # maximal order has it as its right (left) order
          if O === M
            @test is_principal(I) == fl
            @test is_principal(J; side = :left) == fl
            flJ, gamma = is_principal_with_data(J; side = :left)
            @test flJ == fl
            flJ && @test M * gamma == J
          end
        end
        # the orders being fixed, both answers occur on every run
        @test 0 < nprincipal < length(right)
      end
    end
  end

  @testset "over QQ, the default order and non-invertible ideals" begin
    # with no order given, a left ideal is tested over its left order and a
    # right ideal over its right order; O is not maximal
    A = quaternion_algebra(QQ, -1, -1)
    O = order(A, basis(A))
    x = 1 + 2 * basis(A)[2]
    I = O * x
    @test is_principal(I; side = :left)
    fl, beta = is_principal_with_data(I; side = :left)
    @test fl && O * beta == I
    J = x * O
    @test is_principal(J)
    fl, beta = is_principal_with_data(J)
    @test fl && beta * O == J
    # 3M, an ideal of Z + 3M that is not invertible: [Z + 3M : 3M] = 3 is not
    # a square, so it is not principal there, though it is 3 times M, its left
    # and right order
    M = ibukiyama_order(11)
    A = algebra(M)
    Z3M = order(A, vcat([one(A)], [3 * elem_in_algebra(b) for b in basis(M)]))
    I = Hecke.ideal_from_lattice_gens(A, Z3M, [3 * elem_in_algebra(b)
                                                for b in basis(M)])
    @test norm(I, Z3M) == 3
    @test !is_principal(I, Z3M)
    @test !is_principal(I, Z3M; side = :left)
    @test !is_principal_with_data(I, Z3M; side = :left)[1]
    @test is_principal(I) && is_principal(I; side = :left)
    # left ideals only in totally definite algebras
    M = maximal_order(quaternion_algebra(QQ, -1, 3))
    @test_throws ArgumentError is_principal(1 * M, M; side = :left)
    @test_throws ArgumentError is_principal_with_data(1 * M, M; side = :left)
  end

  @testset "over QQ, class numbers" begin
    # the number of right ideal classes of a maximal order of the algebra
    # ramified at p, (p - 1)/12 rounded up but +1 for p = 11 mod 12 (Voight,
    # Quaternion Algebras, Theorem 30.1.5 and Exercise 30.6); right_class_set
    # compares its ideals with this test
    for (p, h) in [(2, 1), (3, 1), (5, 1), (7, 1), (11, 2), (13, 1), (17, 2),
                   (19, 2), (23, 3), (37, 3), (47, 5), (61, 5), (71, 7)]
      O = maximal_order(definite_algebra(p))
      @test length(Hecke.right_class_set(O)) == h
    end
  end

  @testset "over a totally real field, against the generic test" begin
    K, a = quadratic_field(5)
    R = maximal_order(K)
    # fixed maximal orders, as above: the pseudo-bases that maximal_order(A)
    # returned once, all of whose coefficient ideals are R. In (-1, -23),
    # ramified only at the two real places, the test ideals of both orders are
    # principal; in (-1, -11), ramified at the two primes above 11, some are
    # not. The Eichler orders have level the prime above 11 containing
    # sqrt(5) - 4 (4^2 = 5 mod 11), and the prime above 5.
    h = K(1)//2
    X1 = matrix(K, 4, 4, [1, 0, 0, 0, 0, 1, 0, 0, 0, h, h, 0,
                          h, (a + 3)//4, (17 * a + 23)//92, K(1)//46])
    X2 = matrix(K, 4, 4, [1, 0, 0, 0, 0, 1, 0, 0, 0, h, h, 0, h, 0, 0, h])
    P11 = first(P for (P, _) in prime_decomposition(R, 11) if R(a - 4) in P)
    P5 = prime_decomposition(R, 5)[1][1]
    nprincipal = 0
    ntotal = 0
    for (b, X, P) in [(-23, X1, P11), (-11, X2, P5)]
      A = quaternion_algebra(K, -1, b)
      M = order(A, pseudo_matrix(X, [1 * R for i in 1:4]))
      @test is_maximal(M)
      AQ, AQtoA = restrict_scalars(A, QQ)
      for O in [M, eichler(M, P)]
        OQ = order(AQ, preimage.(Ref(AQtoA),
                                 elem_in_algebra.(absolute_basis(O))))
        right, left = test_ideals(O)
        for (I, J) in zip(right, left)
          fl, beta = Hecke._is_principal_with_data(I, O)
          nprincipal += fl
          ntotal += 1
          BQ = preimage.(Ref(AQtoA), absolute_basis(I))
          IQ = Hecke.ideal_from_lattice_gens(AQ, OQ, BQ)
          @test fl == Hecke._is_principal_with_data_bj(IQ, OQ)[1]
          fl && @test beta * O == I
          flJ, gamma = Hecke._is_principal_with_data(J, O; side = :left)
          @test flJ == fl
          flJ && @test O * gamma == J
        end
      end
    end
    # the orders being fixed, both answers occur on every run
    @test 0 < nprincipal < ntotal
  end

  A = definite_algebra(5)
  M = maximal_order(A)
  @test_throws ArgumentError Hecke._is_principal(1 * M, M; side = :both)
end
